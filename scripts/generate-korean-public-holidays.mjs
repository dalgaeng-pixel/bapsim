import Holidays from "date-holidays";
import { writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const START_YEAR = 2024;
const END_YEAR = 2050;
const holidays = new Holidays("KR", { languages: "ko" });
const calendar = new Map();

function addDays(dateKey, offset) {
  const [year, month, day] = dateKey.split("-").map(Number);
  const date = new Date(Date.UTC(year, month - 1, day + offset));
  return date.toISOString().slice(0, 10);
}

function addHoliday(date, name) {
  const existing = calendar.get(date);
  if (!existing) {
    calendar.set(date, name);
    return;
  }

  if (!existing.includes(name)) {
    calendar.set(date, `${existing}·${name}`);
  }
}

for (let year = START_YEAR; year <= END_YEAR; year += 1) {
  for (const holiday of holidays.getHolidays(year).filter((item) => item.type === "public")) {
    const date = holiday.date.slice(0, 10);

    // The library represents Seollal as a three-day duration anchored on New Year's Day.
    // Korean law treats the day before, the day itself, and the day after as public holidays.
    if (holiday.rule.startsWith("korean 01-0-01 P3D")) {
      for (const offset of [-1, 0, 1]) {
        addHoliday(addDays(date, offset), holiday.name);
      }
      continue;
    }

    // Chuseok is correctly anchored on the day before Chuseok and spans three days.
    if (holiday.rule.startsWith("korean 8-0-14 P3D")) {
      for (const offset of [0, 1, 2]) {
        addHoliday(addDays(date, offset), holiday.name);
      }
      continue;
    }

    addHoliday(date, holiday.name);
  }
}

const rows = [...calendar.entries()]
  .sort(([left], [right]) => left.localeCompare(right))
  .map(([date, name]) => `  ${JSON.stringify(date)}: ${JSON.stringify(name)},`)
  .join("\n");

const output = `// Generated by scripts/generate-korean-public-holidays.mjs from date-holidays.\n// Covers ${START_YEAR}-${END_YEAR}; update the generator package data when Korean holiday laws change.\n\nexport const KOREAN_PUBLIC_HOLIDAYS: Record<string, string> = {\n${rows}\n};\n\nexport function getKoreanPublicHolidayName(date: string) {\n  return KOREAN_PUBLIC_HOLIDAYS[date];\n}\n\nexport function isKoreanPublicHoliday(date: string) {\n  return Boolean(getKoreanPublicHolidayName(date));\n}\n`;

await writeFile(resolve("lib/korean-public-holidays.ts"), output, "utf8");